"""Read-only association previews over fictional, isolated temporary databases."""
import hashlib
import unittest
from unittest.mock import patch

from fastapi.testclient import TestClient

import test_v02 as fixtures
from v02.api import create_app
from v02.contracts import provenance


AT = "2026-01-01T10:00:00Z"
DUE = "2026-01-01T11:00:00Z"
PREFIX = "/api/v0.2"


class AssociationPreviewTests(unittest.TestCase):
    tearDown = fixtures.CanonicalTests.tearDown
    memory = fixtures.CanonicalTests.memory
    context_run = fixtures.CanonicalTests.context_run
    attempt = fixtures.CanonicalTests.attempt
    observe = fixtures.CanonicalTests.observe

    def setUp(self):
        for name in ("v02.service.now", "v02.policy.now", "v02.contracts.now"):
            clock = patch(name, return_value=AT)
            clock.start()
            self.addCleanup(clock.stop)
        # Provenance.created_at captures its default factory at model creation;
        # freeze the explicit service helper as well as the edge decay clock.
        def fixed_provenance(*args, **kwargs):
            value = provenance(*args, **kwargs)
            value["created_at"] = AT
            return value
        clock = patch("v02.service.provenance", side_effect=fixed_provenance)
        clock.start()
        self.addCleanup(clock.stop)
        fixtures.CanonicalTests.setUp(self)
        credentials = []
        for token, principal, permissions in (
            ("demo-learner", self.p, ["read", "learn"]),
            ("demo-reader", self.p, ["read"]),
            ("demo-other-owner", "demo:other-owner", ["read", "learn"]),
        ):
            credentials.append({"token_sha256": hashlib.sha256(token.encode()).hexdigest(),
                "principal_id": principal, "host_id": "host", "permissions": permissions})
        self.client = TestClient(create_app(self.service, credentials))
        self.addCleanup(self.client.close)

    def call(self, route, request, *, token="demo-learner", status=200):
        response = self.client.post(PREFIX + route, json=request,
            headers={"Authorization": "Bearer " + token} if token else {})
        self.assertEqual(response.status_code, status, response.text)
        return response.json()

    def snapshot(self):
        # Compare every logical table (including audit, FTS and receipts), not
        # only edge count. All content here was generated by this fixture.
        with self.service.db.connection() as con:
            return tuple(con.iterdump())

    def request(self, key="demo:edge", **changes):
        return {"idempotency_key": key, "reason": "Fictional association review", "from_id": "m1",
                "to_id": "m2", "relation": "co_occurrence", "evidence_refs": ["u1"],
                "expected_version": None, **changes}

    def paired(self, *, second_content="Fictional lighthouse beside a harbor.", extra_source=False):
        refs = ["u1"]
        if extra_source:
            self.service.sync(self.p, {"conversation_id": "chat", "messages": [
                {"id": "demo:u2", "role": "user", "content": "Fictional second beacon observation."}],
                "active_event_ids": ["u1", "demo:u2"], "revision_key": "r2", "expected_revision": "r1",
                "auto_capture": False})
            refs.append("demo:u2")
        self.memory(source_event_ids=refs)
        self.memory(id="m2", content=second_content, source_event_ids=refs)

    def test_preview_works_with_learning_disabled_and_changes_no_logical_data(self):
        self.paired()
        self.service.graph_learning = False
        before = self.snapshot()
        direct = self.service.learn_edge(self.p, self.request(), shadow=True)
        api = self.call("/edges/preview", self.request())
        self.assertEqual(direct, api)
        self.assertTrue(api["would_update"])
        self.assertEqual(api["mode"], "shadow")
        self.assertFalse(api["writes_persistent_state"])
        self.assertEqual(api["proposed"]["strength"], .1)
        self.assertEqual(api["proposed"]["provenance"]["cause_refs"], ["u1"])
        self.assertEqual(api["endpoint_refs"], [{"id": "m1", "version": 1}, {"id": "m2", "version": 1}])
        self.assertEqual(api["path_revision"], "r1")
        self.call("/edges", self.request(), status=422)
        self.assertEqual(self.snapshot(), before)

    def test_preview_requires_learn_permission_and_owned_endpoints(self):
        self.paired()
        before = self.snapshot()
        self.call("/edges/preview", self.request(), token=None, status=401)
        self.call("/edges/preview", self.request(), token="demo-reader", status=403)
        self.call("/edges/preview", self.request(), token="demo-other-owner", status=404)
        self.assertEqual(self.snapshot(), before)

    def test_duplicate_support_has_no_update_even_under_a_new_command_key(self):
        self.paired()
        edge = self.call("/edges", self.request())
        self.service.graph_learning = False
        before = self.snapshot()
        result = self.call("/edges/preview", self.request("demo:duplicate", expected_version=edge["version"]))
        self.assertFalse(result["would_update"])
        self.assertEqual(result["reason"], "support_already_recorded")
        self.assertEqual(result["proposed"], edge["data"])
        self.assertEqual(result["endpoint_refs"], [{"id": "m1", "version": 1}, {"id": "m2", "version": 1}])
        self.assertEqual(result["path_revision"], "r1")
        for stale_version in (None, 2):
            self.call("/edges/preview", self.request("demo:duplicate-stale-" + str(stale_version),
                expected_version=stale_version), status=409)
        self.assertEqual(self.snapshot(), before)

    def test_preview_matches_initial_live_and_subsequent_increment_at_fixed_time(self):
        self.paired(extra_source=True)
        before = self.snapshot()
        preview = self.call("/edges/preview", self.request())
        self.assertEqual(self.snapshot(), before)
        first = self.call("/edges", self.request())
        self.assertEqual(first["data"], preview["proposed"])
        update = self.request("demo:new-support", evidence_refs=["demo:u2"], expected_version=1)
        before_update = self.snapshot()
        preview_update = self.call("/edges/preview", update)
        self.assertEqual(self.snapshot(), before_update)
        second = self.call("/edges", update)
        self.assertEqual(second["data"], preview_update["proposed"])
        self.assertEqual(second["version"], 2)
        self.assertAlmostEqual(second["data"]["strength"], .19)
        for identity in ("m1", "m2"):
            data = self.service.get(self.p, identity)["data"]
            self.assertEqual(data["retrieval_weight"], .2)
            self.assertEqual(data["salience"], .4)
            self.assertEqual(data["generalization_weight"], 0.)
            self.assertIsNone(data["assessment"]["score"])

    def test_preview_checks_missing_and_stale_expected_versions_without_receipts(self):
        self.paired(extra_source=True)
        before = self.snapshot()
        self.call("/edges/preview", self.request(expected_version=1), status=409)
        self.assertEqual(self.snapshot(), before)
        self.call("/edges", self.request())
        before = self.snapshot()
        for version in (None, 2):
            self.call("/edges/preview", self.request("demo:stale-" + str(version),
                evidence_refs=["demo:u2"], expected_version=version), status=409)
        self.assertEqual(self.snapshot(), before)

    def test_graph_induced_corecall_cannot_reinforce_itself_in_preview(self):
        self.paired(second_content="Fictional unrelated harbor record.")
        self.call("/edges", self.request())
        run = self.context_run(graph_hops=1)
        self.attempt(run)
        self.observe(run)
        self.service.graph_learning = False
        before = self.snapshot()
        result = self.call("/edges/preview", self.request("demo:self-induced", relation="co_recall",
                           run_id=run["id"]), status=422)
        self.assertIn("reinforce itself", str(result))
        self.assertEqual(self.snapshot(), before)

    def test_state_induced_corecall_is_not_independent_support(self):
        self.paired()
        self.service.functional_state(self.p, "demo:state", {"idempotency_key": "demo:state",
            "reason": "Fictional temporary attention", "scope": {"conversation_id": "chat"},
            "expiry": DUE, "values": {"attention_urgency": .5}})
        run = self.context_run()
        self.attempt(run)
        self.observe(run)
        self.service.graph_learning = False
        before = self.snapshot()
        result = self.call("/edges/preview", self.request("demo:state-induced", relation="co_recall",
                           run_id=run["id"]), status=422)
        self.assertIn("not independent", str(result))
        self.assertEqual(self.snapshot(), before)

    def test_corecall_needs_final_input_observation_then_can_preview_without_writing(self):
        self.paired()
        run = self.context_run()
        req = self.request("demo:co-recall", relation="co_recall", run_id=run["id"])
        before = self.snapshot()
        self.call("/edges/preview", req, status=422)
        self.assertEqual(self.snapshot(), before)
        self.attempt(run)
        self.observe(run)
        before = self.snapshot()
        result = self.call("/edges/preview", req)
        self.assertTrue(result["would_update"])
        self.assertEqual(result["proposed"]["relation"], "co_recall")
        self.assertEqual(self.snapshot(), before)

    def test_temporal_preview_requires_forward_distinct_sources_on_current_path(self):
        self.service.sync(self.p, {"conversation_id": "chat", "messages": [
            {"id": "demo:later", "role": "user", "content": "Fictional later lighthouse observation"}],
            "active_event_ids": ["u1", "demo:later"], "revision_key": "r2", "expected_revision": "r1",
            "auto_capture": False})
        self.memory()
        self.memory(id="m2", source_event_ids=["demo:later"])
        req = self.request(relation="temporal_next", evidence_refs=["u1", "demo:later"])
        before = self.snapshot()
        self.assertTrue(self.call("/edges/preview", req)["would_update"])
        self.call("/edges/preview", {**req, "from_id": "m2", "to_id": "m1"}, status=422)
        self.assertEqual(self.snapshot(), before)
        self.service.sync(self.p, {"conversation_id": "chat", "messages": [], "active_event_ids": ["demo:later"],
            "revision_key": "r3", "expected_revision": "r2", "auto_capture": False})
        before = self.snapshot()
        self.call("/edges/preview", req, status=422)
        self.assertEqual(self.snapshot(), before)


if __name__ == "__main__":
    unittest.main()
